import { readFile, access } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import path from 'node:path';
const root=fileURLToPath(new URL('../',import.meta.url));
const pkg=JSON.parse(await readFile(path.join(root,'package.json'),'utf8'));
for(const file of ['src/plugin.js','src/service.js','src/calendar.js','src/providers/zydx.js','src/analysis.js','src/timeline.js','src/report.js','src/cli.js','skills/bazi/SKILL.md','skills/bazi/references/interpretation.md','cordis.patch.yml','LICENSE','NOTICE','README.md']) await access(path.join(root,file));
if(pkg.dsh?.bundle?.patch!=='./cordis.patch.yml') throw new Error('Missing dsh bundle patch');
const plugin=await import('../src/plugin.js');
if(typeof plugin.apply!=='function') throw new Error('Plugin must export apply');
console.log(`Package verified: ${pkg.name}@${pkg.version}`);
